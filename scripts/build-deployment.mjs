import { readFile, writeFile, readdir, mkdir, copyFile, stat, rm } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import { brotliCompressSync, brotliDecompressSync, constants } from 'node:zlib';
import { build } from 'esbuild';
import { buildFooterEffects } from './build-footer-effects.mjs';
import { showProjects } from '../site-features.mjs';
import { buildServicesCarousel } from './build-services-carousel.mjs';
import { buildBlogCovers } from './build-blog-covers.mjs';
import { dispatchPosts } from '../blog-dispatch.mjs';
import { heroMedia } from '../hero-media.mjs';

const project = path.resolve('.');
const output = path.join(project,'dist');
// Only this builder's previously generated output may be replaced.
if (output !== path.join(project,'dist') || path.dirname(output) !== project) throw new Error('Invalid output directory');
const exists = await stat(output).then(() => true).catch(() => false);
if (exists) {
  const marker = await readFile(path.join(output,'deployment-report.json'),'utf8').then(JSON.parse).catch(() => null);
  if (marker?.generatedBy !== 'lyman-deployment-builder') throw new Error('dist already exists and is not generated by this builder');
  await rm(output,{recursive:true});
}
await mkdir(path.join(output,'public'),{recursive:true});
await buildServicesCarousel();
await buildBlogCovers();
await buildFooterEffects();
const manifest = JSON.parse(await readFile('mirror-manifest.json','utf8'));
const routes = manifest.routes.filter(route => {
  if (!showProjects && /^\/projects(?:\/|$)/.test(route)) return false;
  const blog = route.match(/^\/blog\/([^/]+)$/)?.[1];
  if (blog && !dispatchPosts.some(post => post.slug === blog)) return false;
  return !/^\/projects\/(zypher|grotesks|clonify|polltree)$/.test(route);
});
const aliases = {};
const skipped = new Set();
const optimized = [];
let sourcePublicBytes = 0;
let deploymentBytes = 0;
let imageBytesSaved = 0;
let textBytesSaved = 0;
let compressedTextFiles = 0;

async function files(dir) {
  const list = [];
  for (const entry of await readdir(dir,{withFileTypes:true})) {
    const name = path.join(dir,entry.name);
    if (entry.isDirectory()) list.push(...await files(name));
    else list.push(name);
  }
  return list;
}
async function emit(relative,bytes) {
  const destination = path.join(output,relative);
  await mkdir(path.dirname(destination),{recursive:true});
  await writeFile(destination,bytes);
  deploymentBytes += bytes.length;
}

// These old hero assets are used only on the homepage and have already been
// replaced in the current design. Retain their URLs as aliases for hydration.
for (const item of heroMedia) {
  const originals = (await files('public/_assets')).filter(file => path.basename(file) === item.original);
  for (const file of originals) {
    skipped.add(file);
    aliases['/'+path.relative('public',file).replaceAll('\\','/')] = `/_assets/hero/${item.video || item.name+'.webp'}`;
  }
}
for (const post of dispatchPosts) {
  for (const file of (await files('public/_assets')).filter(file => path.basename(file) === post.originalCover)) {
    skipped.add(file);
    aliases['/'+path.relative('public',file).replaceAll('\\','/')] = `/_assets/blog-covers/${post.cover}-1440.webp`;
  }
}

for (const file of await files('public')) {
  sourcePublicBytes += (await stat(file)).size;
  const relative = path.relative('public',file).replaceAll('\\','/');
  if (skipped.has(file)) continue;
  if (relative.endsWith('/index.html') || relative === 'index.html') {
    const route = relative === 'index.html' ? '/' : '/'+relative.slice(0,-'/index.html'.length);
    if (!routes.includes(route)) continue;
  }
  const bytes = await readFile(file);
  let deployedRelative = 'public/'+relative;
  if (path.extname(file).toLowerCase() === '.png') {
    const webp = await sharp(bytes).keepMetadata().webp({lossless:true,effort:6}).toBuffer();
    if (webp.length < bytes.length) {
      // Compare rendered pixels before accepting a lossless conversion.
      const before = await sharp(bytes).ensureAlpha().raw().toBuffer({resolveWithObject:true});
      const after = await sharp(webp).ensureAlpha().raw().toBuffer({resolveWithObject:true});
      let same = before.info.width === after.info.width && before.info.height === after.info.height;
      for (let i=0;same && i<before.data.length;i+=4) {
        same = before.data[i+3] === after.data[i+3] && (before.data[i+3] === 0 || (before.data[i] === after.data[i] && before.data[i+1] === after.data[i+1] && before.data[i+2] === after.data[i+2]));
      }
      if (same) {
        const replacement = relative.replace(/\.png$/i,'.lossless.webp');
        aliases['/'+relative] = '/'+replacement;
        imageBytesSaved += bytes.length-webp.length;
        optimized.push({source:relative,output:replacement,before:bytes.length,after:webp.length,pixelsIdentical:true});
        await emit('public/'+replacement,webp);
        continue;
      }
    }
  }
  if (/\.(?:html|js|mjs|css|svg|json|txt)$/.test(file) && bytes.length > 1024) {
    const br = brotliCompressSync(bytes,{params:{[constants.BROTLI_PARAM_QUALITY]:11}});
    if (br.length < bytes.length) {
      if (!brotliDecompressSync(br).equals(bytes)) throw new Error(`Compression changed ${relative}`);
      textBytesSaved += bytes.length - br.length;
      compressedTextFiles++;
      await emit(deployedRelative+'.br',br);
      continue;
    }
  }
  await emit(deployedRelative,bytes);
}
await emit('public/deployment-assets.json',Buffer.from(JSON.stringify(aliases)));
const serverBundle = await build({entryPoints:['server.mjs'],bundle:true,minify:true,platform:'node',format:'esm',target:'node22',write:false});
await emit('server.mjs',serverBundle.outputFiles[0].contents);
await emit('package.json',Buffer.from(JSON.stringify({name:'lyman-studio',version:'1.0.0',private:true,type:'module',engines:{node:'>=22'},scripts:{start:'node start.mjs'}},null,2)));
await emit('start.mjs',Buffer.from("process.env.NODE_ENV ||= 'production';\nawait import('./server.mjs');\n"));
await emit('Dockerfile',Buffer.from('FROM node:22-alpine\nWORKDIR /app\nCOPY . .\nENV NODE_ENV=production\nEXPOSE 3000\nCMD ["node", "start.mjs"]\n'));
await emit('README.md',Buffer.from('# Lyman Studio deployment\n\nDeploy this folder to a Node.js host. No npm install is needed: run `npm start`. The server uses `PORT` and binds to all interfaces in production. Node.js 22+ is required.\n\nThis package preserves the original Framer motion and CMS protocol, videos, and custom React carousel. A static-only host cannot run its CMS range protocol.\n\nImages converted to WebP retain identical visible pixels and full resolution. Old image URLs are mapped transparently. Videos are not recompressed. Text assets are stored as a single lossless Brotli copy; the server also supports gzip and uncompressed requests. The editable source and hidden project content remain in the source repository.\n'));
const report = {generatedBy:'lyman-deployment-builder',sourcePublicBytes,deploymentBytes,imageBytesSaved,textBytesSaved,compressedTextFiles,excludedReplacedMediaBytes:(await Promise.all([...skipped].map(async file => (await stat(file)).size))).reduce((a,b)=>a+b,0),routes,optimizedImages:optimized};
await writeFile(path.join(output,'deployment-report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({folder:output,sourcePublicMB:+(sourcePublicBytes/1048576).toFixed(2),deploymentMB:+(deploymentBytes/1048576).toFixed(2),losslessImages:optimized.length,imageSavingsMB:+(imageBytesSaved/1048576).toFixed(2),textSavingsMB:+(textBytesSaved/1048576).toFixed(2),compressedTextFiles,replacedMediaMB:+(report.excludedReplacedMediaBytes/1048576).toFixed(2)},null,2));
