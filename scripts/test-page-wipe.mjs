const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.route(/^https?:/,route=>route.abort());
await page.goto('file:///C:/Users/ADMIN/bungee-clone/index.html');
await page.locator('[data-framer-name="Portfolio"] a[href]').filter({visible:true}).first().click();
await page.waitForURL('**/preview/projects/things/index.html');
await page.waitForTimeout(1000);
const project=page.url();
await page.goBack();await page.waitForTimeout(1000);
const remainingCurtains=await page.locator('[data-page-curtain]').count();
console.log(JSON.stringify({project,returned:page.url(),remainingCurtains,errors}));
await browser.close();if(errors.length||remainingCurtains)process.exitCode=1;
